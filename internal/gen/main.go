//go:build ignore

// This program generates list.go by fetching the official IANA TLD list.
// It is invoked by running: go generate
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"strings"
	"time"
)

const ianaURL = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	tlds, version, err := fetchTLDs()
	if err != nil {
		log.Fatalf("failed to fetch TLDs: %v", err)
	}

	if err := generateFile(tlds, version); err != nil {
		log.Fatalf("failed to generate file: %v", err)
	}

	log.Printf("generated list.go with %d TLDs (version: %s)", len(tlds), version)
}

func fetchTLDs() ([]string, string, error) {
	client := &http.Client{Timeout: 30 * time.Second}

	resp, err := client.Get(ianaURL)
	if err != nil {
		return nil, "", fmt.Errorf("HTTP request failed: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, "", fmt.Errorf("unexpected status code: %d", resp.StatusCode)
	}

	var tlds []string
	var version string

	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		// First line is a comment with version info
		if strings.HasPrefix(line, "#") {
			version = strings.TrimPrefix(line, "# ")
			continue
		}
		// Convert to lowercase for consistent matching
		tlds = append(tlds, strings.ToLower(line))
	}

	if err := scanner.Err(); err != nil {
		return nil, "", fmt.Errorf("failed to read response: %w", err)
	}

	return tlds, version, nil
}

func generateFile(tlds []string, version string) error {
	var buf bytes.Buffer

	fmt.Fprintf(&buf, `// Code generated by go generate; DO NOT EDIT.
// Source: %s
// %s

package tld

var validTLDs = map[string]struct{}{
`, ianaURL, version)

	for _, tld := range tlds {
		fmt.Fprintf(&buf, "\t%q: {},\n", tld)
	}

	buf.WriteString("}\n")

	// Format the generated code
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("failed to format source: %w", err)
	}

	if err := os.WriteFile("list.go", formatted, 0o644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}

	return nil
}

